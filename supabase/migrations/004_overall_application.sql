create table if not exists public.audit_log (
  id bigint generated by default as identity primary key,
  table_name text not null,
  record_id text,
  action text not null,
  changed_by text,
  old_data jsonb,
  new_data jsonb,
  created_at timestamptz not null default now()
);
create index if not exists idx_audit_table_record on public.audit_log(table_name,record_id,created_at desc);

create or replace function public.audit_accession_changes() returns trigger
language plpgsql security definer as $$
begin
  if tg_op='INSERT' then
    insert into public.audit_log(table_name,record_id,action,new_data) values (tg_table_name,new.id::text,'INSERT',to_jsonb(new));
    return new;
  elsif tg_op='UPDATE' then
    insert into public.audit_log(table_name,record_id,action,old_data,new_data) values (tg_table_name,new.id::text,'UPDATE',to_jsonb(old),to_jsonb(new));
    return new;
  elsif tg_op='DELETE' then
    insert into public.audit_log(table_name,record_id,action,old_data) values (tg_table_name,old.id::text,'DELETE',to_jsonb(old));
    return old;
  end if;
  return null;
end; $$;

drop trigger if exists trg_accessions_audit on public.accessions;
create trigger trg_accessions_audit after insert or update or delete on public.accessions for each row execute function public.audit_accession_changes();

