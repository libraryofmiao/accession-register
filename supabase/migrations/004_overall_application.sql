-- Overall Accession Register application foundation.
-- Adds hierarchical locations, DDC structure, settings, audit trail and reporting indexes.

alter table public.location_master add column if not exists section_name text;
alter table public.location_master add column if not exists rack_name text;
create index if not exists idx_location_section_rack_shelf on public.location_master(section_name,rack_name,shelf);

alter table public.ddc_master add column if not exists division_number text;
alter table public.ddc_master add column if not exists section_number text;
create index if not exists idx_ddc_division on public.ddc_master(division_number);
create index if not exists idx_ddc_section on public.ddc_master(section_number);

create table if not exists public.ddc_divisions (
  id bigint generated by default as identity primary key,
  division_number text not null unique,
  name text not null,
  created_at timestamptz not null default now()
);

create table if not exists public.ddc_sections (
  id bigint generated by default as identity primary key,
  section_number text not null unique,
  division_number text not null,
  caption text,
  status text not null default 'Needs licensed/source caption',
  created_at timestamptz not null default now()
);
create index if not exists idx_ddc_sections_division on public.ddc_sections(division_number);

-- Create the complete numeric 000-999 section framework without reproducing copyrighted captions.
insert into public.ddc_sections(section_number,division_number)
select lpad(n::text,3,'0'), lpad(((n/10)*10)::text,3,'0')
from generate_series(0,999) as g(n)
on conflict (section_number) do nothing;

create table if not exists public.app_settings (
  key text primary key,
  value text not null default '',
  updated_at timestamptz not null default now()
);
